function defaults = build_exit_plane_analysis_defaults(Nx, Ny, thickness_map, circle_mask_board, dx, dz, net_num_board)
thickness_mm = double(thickness_map) * 1e3;
[thickness_grad_x, thickness_grad_y] = gradient(double(thickness_map));
thickness_grad_norm = hypot(thickness_grad_x, thickness_grad_y) / (dz + eps);

window_kernel = ones(5, 5);
window_count = conv2(double(circle_mask_board), window_kernel, 'same');
local_thickness_mean = conv2(double(thickness_map) .* double(circle_mask_board), window_kernel, 'same') ./ (window_count + eps);
local_thickness_var = conv2(((double(thickness_map) - local_thickness_mean).^2) .* double(circle_mask_board), window_kernel, 'same') ./ (window_count + eps);
local_thickness_std = sqrt(max(local_thickness_var, 0)) * 1e3;
aperture_edge_distance_px = bwdist(~circle_mask_board);
aperture_edge_distance_mm = aperture_edge_distance_px * dx * 1e3;
unique_layers = unique(net_num_board(circle_mask_board));

defaults = struct();
defaults.p_exit_complex = zeros(Nx, Ny);
defaults.p_exit_amp = zeros(Nx, Ny);
defaults.p_exit_amp_norm = zeros(Nx, Ny);
defaults.p_exit_phase = zeros(Nx, Ny);
defaults.exit_amp_cv = NaN;
defaults.exit_amp_min_ratio = NaN;
defaults.thickness_mm = thickness_mm;
defaults.thickness_grad_norm = thickness_grad_norm;
defaults.local_thickness_mean = local_thickness_mean;
defaults.local_thickness_std = local_thickness_std;
defaults.aperture_edge_distance_mm = aperture_edge_distance_mm;
defaults.valid_exit_mask = false(Nx, Ny);
defaults.thickness_vals_mm = zeros(0, 1);
defaults.grad_vals = zeros(0, 1);
defaults.exit_amp_vals = zeros(0, 1);
defaults.local_mean_vals_mm = zeros(0, 1);
defaults.local_std_vals_mm = zeros(0, 1);
defaults.edge_dist_vals_mm = zeros(0, 1);
defaults.edge_amp_mean = NaN;
defaults.flat_amp_mean = NaN;
defaults.thickness_amp_corr = NaN;
defaults.grad_amp_corr = NaN;
defaults.local_mean_amp_corr = NaN;
defaults.local_std_amp_corr = NaN;
defaults.edge_dist_amp_corr = NaN;
defaults.exit_amp_model_r2 = NaN;
defaults.unique_layers = unique_layers;
defaults.layer_mean_amp = NaN(numel(unique_layers), 1);
defaults.layer_std_amp = NaN(numel(unique_layers), 1);
defaults.layer_mean_thickness_mm = NaN(numel(unique_layers), 1);
defaults.thickness_scatter_mm = zeros(0, 1);
defaults.grad_scatter = zeros(0, 1);
defaults.exit_amp_scatter = zeros(0, 1);
defaults.local_std_scatter_mm = zeros(0, 1);
defaults.edge_dist_scatter_mm = zeros(0, 1);
defaults.model_pred_scatter = zeros(0, 1);
defaults.board_exit_asm_amp = zeros(Nx, Ny);
defaults.board_exit_asm_norm = zeros(Nx, Ny);
defaults.board_exit_asm_pcc = NaN;
defaults.board_exit_kwave_corr = NaN;
end
